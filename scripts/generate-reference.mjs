#!/usr/bin/env node
// Generates docs/REFERENCE.md: every skill and agent, grouped, with what it does, what it produces, and its tools.
// Reads catalog/catalog.json, skills/*/SKILL.md and agents/*.md, so it cannot drift from the real files.
// Usage: node scripts/generate-reference.mjs
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cat = JSON.parse(readFileSync(join(root, 'catalog', 'catalog.json'), 'utf8'));
const field = (text, key) => (text.match(new RegExp(`^${key}:\\s*(.+)$`, 'm')) || [, ''])[1].trim();
const cell = (s) => s.replace(/\|/g, '\\|');

// Stage skills written before the "Produces:" line existed.
const PRODUCES_FALLBACK = {
  'aidlc-plan': '`intent.md`', 'aidlc-design': '`spec.md`', 'aidlc-build': '`plan.md`, the diff and tests',
  'aidlc-test': '`test-report.md`', 'aidlc-deploy': '`review-findings.md`, `release.md`', 'aidlc-maintain': '`incident.md`, a new `intent.md`',
  'aidlc-workflow': '`docs/aidlc/status.md` (tracker)', 'aidlc-project-context': '`AGENTS.md`', 'aidlc-review-policy': '`REVIEW.md`',
  'aidlc-policy-skill': 'a policy skill', 'aidlc-guardrails': 'guard checks and CI gates', 'aidlc-evals': '`evals/` files',
  'aidlc-metrics': '`docs/aidlc/metrics/<month>.md`', 'aidlc-connectors': 'connector rules and links',
  'git-commit': 'a branch and commits', 'git-create-pr': 'a pull request', 'git-review-pr': 'a review on the pull request',
  'git-pr-comment': 'comments and replies', 'git-resolve-pr-conflicts': 'a conflict-free branch', 'git-release-notes': '`CHANGELOG.md`, tag, release',
};

const skillRows = (stage) => Object.keys(cat.skills).filter((n) => cat.skills[n].stage === stage).sort().map((n) => {
  const text = readFileSync(join(root, 'skills', n, 'SKILL.md'), 'utf8');
  const m = text.match(/Produces:\s*(.+?)\.\s*$/m);
  const produces = m ? m[1] : PRODUCES_FALLBACK[n] || '—';
  return `| \`/${n}\` | ${cell(field(text, 'description'))} | ${cell(produces)} |`;
});

const lines = [];
lines.push('# Skills and agents reference', '',
  '*Generated by `node scripts/generate-reference.mjs` from `catalog/catalog.json`, `skills/` and `agents/`. Do not edit by hand. For concepts and how it all fits together, read [GUIDE.md](GUIDE.md).*', '');
const nSkills = Object.keys(cat.skills).length, nAgents = Object.keys(cat.agents).length;
lines.push(`**${nSkills} skills and ${nAgents} agents** in ${cat.stages.length} groups.`, '');
lines.push('## Contents', '', ...cat.stages.map((s) => `- [${s.label}](#${s.label.toLowerCase().replace(/[^a-z0-9]+/g, '-')}) (${Object.values(cat.skills).filter((v) => v.stage === s.id).length})`), '- [Agents](#agents)', '- [Role presets](#role-presets)', '');

for (const s of cat.stages) {
  lines.push(`## ${s.label}`, '', '| Skill (type it as a slash command) | What it does | Produces |', '|---|---|---|', ...skillRows(s.id), '');
}

lines.push('## Agents', '',
  'An agent is a focused helper with its own context and a limited set of tools. A skill tells the assistant **how to do a job**; an agent is **who does a bounded part of it** without seeing, or being able to change, more than it needs. The main assistant session calls agents; agents do not call each other.', '',
  '| Agent | Group | Tools | What it does |', '|---|---|---|---|');
for (const f of readdirSync(join(root, 'agents')).filter((x) => x.endsWith('.md')).sort()) {
  const text = readFileSync(join(root, 'agents', f), 'utf8');
  const name = field(text, 'name');
  const caps = field(text, 'capabilities');
  const stage = cat.stages.find((x) => x.id === cat.agents[name]?.stage)?.label ?? '';
  lines.push(`| \`${name}\` | ${stage} | ${caps} | ${cell(field(text, 'description'))} |`);
}
lines.push('', '**Tools key:** `read` read files; `search` search the code; `edit` change files; `execute` run commands. An agent with only `read, search` cannot change anything.', '');

lines.push('## Role presets', '', 'The picker on the Installation page installs these sets. Edit them in `catalog/catalog.json`.', '', '| Role | Description | Whole groups | Extra skills |', '|---|---|---|---|');
for (const r of cat.roles) {
  lines.push(`| ${r.label} | ${cell(r.description)} | ${r.stages.map((x) => cat.stages.find((y) => y.id === x)?.label).join(', ') || '—'} | ${r.extra.length ? r.extra.map((x) => '`' + x + '`').join(', ') : '—'} |`);
}
lines.push('', `The orchestrator (${cat.core.map((x) => '`' + x + '`').join(', ')}) is always installed.`, '');

mkdirSync(join(root, 'docs'), { recursive: true });
writeFileSync(join(root, 'docs', 'REFERENCE.md'), lines.join('\n'));
console.log(`Wrote docs/REFERENCE.md (${nSkills} skills, ${nAgents} agents)`);
